export function formatRub(value: number): string {
  return `${new Intl.NumberFormat('ru-RU').format(value).replace(/ |\s/g, ' ')} ₽`
}

export function formatUpdated(iso: string): string {
  const [y, m, d] = iso.split('-')
  return `${d}.${m}.${y}`
}
